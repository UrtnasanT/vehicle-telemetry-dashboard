function generateAverage(lap1, lap2) {
  return lap1.map((point, i) => ({
    time: point.time,
    speed_kph: (point.speed_kph + lap2[i].speed_kph) / 2,
    rpm: (point.rpm + lap2[i].rpm) / 2,
    g_force: (point.g_force + lap2[i].g_force) / 2,
    fuel_level_percent:
      (point.fuel_level_percent + lap2[i].fuel_level_percent) / 2,
  }));
}

